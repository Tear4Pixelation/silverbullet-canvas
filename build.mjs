// Bundles the editor into one minified script + stylesheet, then emits:
//   generated/editor_assets.ts  (inlined into the plug by plug-compile)
//   dist/canvas-editor.html     (standalone editor, open it in any browser)
import { build, transform } from "esbuild";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const watch = process.argv.includes("--watch");

const js = await build({
  entryPoints: ["editor/src/main.ts"],
  bundle: true,
  minify: !watch,
  format: "iife",
  target: "es2022",
  loader: { ".canvas": "text" },
  write: false,
  legalComments: "none",
});
const css = await transform(await readFile("editor/src/styles.css", "utf8"), { loader: "css", minify: true });

// Inline <script>/<style> must not contain their own closing tags.
const script = js.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const style = css.code.replace(/<\/style/gi, "<\\/style");

await mkdir("generated", { recursive: true });
await mkdir("dist", { recursive: true });
await writeFile(
  "generated/editor_assets.ts",
  `// Generated by build.mjs, do not edit.\nexport const EDITOR_CSS = ${JSON.stringify(style)};\nexport const EDITOR_JS = ${JSON.stringify(script)};\n`,
);
await writeFile(
  "dist/canvas-editor.html",
  `<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">` +
    `<title>JSON Canvas Editor</title><style>${style}</style></head>` +
    `<body><div id="canvas-root"></div><script>${script}</script></body></html>\n`,
);

// Exactly what the plug's canvasEditor() returns; used by test/harness.html.
await writeFile(
  "dist/plug-editor.html",
  `<!DOCTYPE html><html><head><meta charset="utf-8"><style>${style}</style></head>` +
    `<body><div id="canvas-root"></div><script>${script}</script></body></html>`,
);

// Test harness that mimics SilverBullet's document-editor host (not shipped).
await copyFile("test/harness.html", "dist/harness.html");
await copyFile("editor/demo.canvas", "dist/demo.canvas");

const kb = (text) => (Buffer.byteLength(text) / 1024).toFixed(1) + " kB";
console.log(`editor js ${kb(script)}, css ${kb(style)}`);
