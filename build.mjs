// Bundles the editor (with the CodeMirror card editor) and the read-only viewer
// (for ```canvas previews, no CodeMirror), then emits:
//   generated/editor_assets.ts  (inlined into the plug by plug-compile)
//   dist/canvas-editor.html     (standalone editor, open it in any browser)
//   dist/plug-editor.html, dist/widget.json, dist/harness.html  (test harness)
import { build, transform } from "esbuild";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const minify = !process.argv.includes("--dev");

async function bundle(entry) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    minify,
    format: "iife",
    target: "es2022",
    loader: { ".canvas": "text" },
    write: false,
    legalComments: "none",
  });
  // Inline <script> must not contain its own closing tag.
  return result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
}

const editorJs = await bundle("editor/src/main.ts");
const viewerJs = await bundle("editor/src/widget.ts");
const css = (await transform(await readFile("editor/src/styles.css", "utf8"), { loader: "css", minify })).code
  .replace(/<\/style/gi, "<\\/style");

await mkdir("generated", { recursive: true });
await mkdir("dist", { recursive: true });
await writeFile(
  "generated/editor_assets.ts",
  "// Generated by build.mjs, do not edit.\n" +
    `export const CANVAS_CSS = ${JSON.stringify(css)};\n` +
    `export const EDITOR_JS = ${JSON.stringify(editorJs)};\n` +
    `export const VIEWER_JS = ${JSON.stringify(viewerJs)};\n`,
);
await writeFile(
  "dist/canvas-editor.html",
  `<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">` +
    `<title>JSON Canvas Editor</title><style>${css}</style></head>` +
    `<body><div id="canvas-root"></div><script>${editorJs}</script></body></html>\n`,
);

// Same output as the plug's canvasEditor() / showWidget(), for test/harness.html.
await writeFile(
  "dist/plug-editor.html",
  `<!DOCTYPE html><html><head><meta charset="utf-8"><style>${css}</style></head>` +
    `<body><div id="canvas-root"></div><script>${editorJs}</script></body></html>`,
);
await writeFile("dist/widget.json", JSON.stringify({ css, script: viewerJs }));
await copyFile("test/harness.html", "dist/harness.html");
await copyFile("editor/demo.canvas", "dist/demo.canvas");

const kb = (text) => (Buffer.byteLength(text) / 1024).toFixed(1) + " kB";
console.log(`editor js ${kb(editorJs)}, viewer js ${kb(viewerJs)}, css ${kb(css)}`);
